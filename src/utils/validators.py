import pandas as pd  # Работа с табличными данными
from typing import List  # Типизация для списков
from src.utils.logger import get_logger  # Используем наш кастомный логгер

# Получаем логгер для этого модуля
logger = get_logger(__name__)  # Создаем логгер с именем текущего файла (src.utils.validators)


# ==============================================================================
# БЛОК 1: ПРОВЕРКА НА ПРОПУСКИ (NULL VALUES)
# Назначение: Убеждаемся, что критически важные поля не содержат NULL.
# ==============================================================================
def check_nulls(df: pd.DataFrame, columns: List[str]) -> bool:  # Функция возвращает True, если пропусков нет
    """
    Проверяет наличие NULL значений в указанных колонках.

    Args:
        df (pd.DataFrame): Проверяемый DataFrame.
        columns (List[str]): Список колонок для проверки.

    Returns:
        bool: True, если пропусков нет. False, если найдены пропуски.
    """
    logger.info(f"Проверка на пропуски в колонках: {columns}")  # Логируем начало проверки

    # Считаем количество пропусков только в указанных колонках
    null_counts = df[columns].isnull().sum()  # Возвращает Series: {col1: 0, col2: 5}

    # Фильтруем только те колонки, где есть пропуски (> 0)
    cols_with_nulls = null_counts[null_counts > 0]  # Оставляем только проблемные колонки

    if not cols_with_nulls.empty:  # Если есть хотя бы одна колонка с пропусками
        logger.error(
            f"Обнаружены пропуски: {cols_with_nulls.to_dict()}")  # Логируем ошибку со словарем {колонка: количество}
        return False  # Валидация не пройдена

    logger.info("Пропуски в критических полях отсутствуют")  # Логируем успех
    return True  # Валидация пройдена


# ==============================================================================
# БЛОК 2: ПРОВЕРКА НА ДУБЛИКАТЫ (DUPLICATES)
# Назначение: Убеждаемся, что первичный ключ уникален.
# ==============================================================================
def check_duplicates(df: pd.DataFrame, subset: List[str]) -> bool:  # Функция возвращает True, если дубликатов нет
    """
    Проверяет наличие полных дубликатов или дубликатов по подмножеству колонок.

    Args:
        df (pd.DataFrame): Проверяемый DataFrame.
        subset (List[str]): Колонки, по которым ищем дубликаты (обычно первичный ключ).

    Returns:
        bool: True, если дубликатов нет.
    """
    logger.info(f"Проверка на дубликаты по колонкам: {subset}")  # Логируем начало

    # Находим дубликаты
    duplicates = df[df.duplicated(subset=subset, keep=False)]  # keep=False помечает ВСЕ копии дубликата

    duplicate_count = len(duplicates)  # Считаем количество строк-дубликатов

    if duplicate_count > 0:  # Если нашли дубликаты
        logger.error(f"Обнаружено {duplicate_count} строк с дубликатами!")  # Логируем ошибку
        return False  # Валидация не пройдена

    logger.info("Дубликаты отсутствуют")  # Логируем успех
    return True  # Валидация пройдена


# ==============================================================================
# БЛОК 3: ПРОВЕРКА СХЕМЫ ДАННЫХ (SCHEMA CHECK)
# Назначение: Убеждаемся, что в DataFrame есть все нужные колонки.
# ==============================================================================
def check_schema(df: pd.DataFrame,
                 expected_columns: List[str]) -> bool:  # Функция возвращает True, если схема совпадает
    """
    Проверяет, что DataFrame содержит все ожидаемые колонки.

    Args:
        df (pd.DataFrame): Проверяемый DataFrame.
        expected_columns (List[str]): Ожидаемый список колонок.

    Returns:
        bool: True, если все колонки на месте.
    """
    logger.info(f"Проверка схемы данных. Ожидается {len(expected_columns)} колонок")  # Логируем начало

    actual_columns = set(df.columns)  # Превращаем текущие колонки в множество (set)
    expected_set = set(expected_columns)  # Превращаем ожидаемые колонки в множество

    # Ищем колонки, которые ожидаются, но отсутствуют в DataFrame
    missing_columns = expected_set - actual_columns  # Разность множеств

    if missing_columns:  # Если есть недостающие колонки
        logger.error(f"Отсутствуют колонки: {missing_columns}")  # Логируем ошибку
        return False  # Валидация не пройдена

    logger.info("Схема данных соответствует ожиданиям")  # Логируем успех
    return True  # Валидация пройдена