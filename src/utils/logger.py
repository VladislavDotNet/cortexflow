# ==============================================================================
# ФАЙЛ: logger.py
# НАЗНАЧЕНИЕ: Централизованная настройка и предоставление логгеров.
# ОПИСАНИЕ: Инициализирует систему логирования Python на основе
#           config/logging_config.yaml. Предоставляет функцию get_logger(),
#           которую нужно вызывать во всех модулях проекта вместо
#           logging.getLogger(__name__). Гарантирует единый формат логов.
# ПРИМЕНЕНИЕ: Импортируется в начале любого модуля:
#             from src.utils.logger import get_logger
# ==============================================================================

import logging  # Стандартная библиотека логирования
import logging.config  # Модуль для настройки логирования через словари/YAML
import yaml  # Парсинг YAML
from pathlib import Path  # Работа с путями

# Импортируем PROJECT_ROOT из config.py, чтобы не дублировать логику поиска корня
from src.utils.config import PROJECT_ROOT


# ==============================================================================
# БЛОК 1: ИНИЦИАЛИЗАЦИЯ ЛОГИРОВАНИЯ
# Назначение: Загрузка конфигурации логов и применение её к Python logging.
# ==============================================================================
def setup_logging():  # Функция настройки логгера
    """
    Настраивает логирование на основе logging_config.yaml.
    Вызывается один раз при старте приложения.
    """
    config_path = PROJECT_ROOT / "config" / "logging_config.yaml"  # Путь к файлу конфига логов

    if config_path.exists():  # Проверяем, существует ли файл
        with open(config_path, 'r', encoding='utf-8') as file:  # Открываем файл
            config = yaml.safe_load(file)  # Парсим YAML

        logging.config.dictConfig(config)  # Применяем словарь конфигурации к logging
    else:  # Если файла нет
        # Используем базовую настройку (fallback), чтобы логи всё равно работали
        logging.basicConfig(  # Базовая настройка
            level=logging.INFO,  # Уровень INFO
            format='%(asctime)s - %(name)s - %(levelname)s - %(message)s',  # Стандартный формат
            datefmt='%Y-%m-%d %H:%M:%S'  # Формат даты
        )


# Вызываем настройку сразу при импорте модуля (гарантирует, что логи настроены)
setup_logging()  # Инициализация системы логирования


# ==============================================================================
# БЛОК 2: ФАБРИЧНАЯ ФУНКЦИЯ ПОЛУЧЕНИЯ ЛОГГЕРА
# Назначение: Предоставление настроенного логгера для конкретного модуля.
# ==============================================================================
def get_logger(name: str) -> logging.Logger:  # Функция возвращает объект Logger
    """
    Возвращает настроенный логгер для указанного модуля.

    Args:
        name (str): Имя логгера (обычно __name__ вызывающего модуля).

    Returns:
        logging.Logger: Объект логгера.
    """
    return logging.getLogger(name)  # Получаем логгер по имени (он уже настроен через dictConfig)